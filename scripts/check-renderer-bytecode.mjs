#!/usr/bin/env node

import { spawn } from "node:child_process";
import { once } from "node:events";
import { writeSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";
import { setFlagsFromString } from "node:v8";
import { Script } from "node:vm";

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = resolve(dirname(scriptPath), "..");
// Leave 12 KiB of growth before V8's default 60 KiB TurboFan cutoff.
const bytecodeBudget = 48 * 1024;
const components = [
  ["DesktopAppShell", "apps/desktop/src/renderer/src/App.tsx"],
  ["Sidebar", "apps/desktop/src/renderer/src/features/navigation/Sidebar.tsx"],
  ["ThreadView", "apps/desktop/src/renderer/src/features/thread-detail/ThreadView.tsx"],
  ["AutomationEditor", "apps/desktop/src/renderer/src/features/automations/AutomationEditor.tsx"],
];

// Match Vitest 5's module-evaluator wrapper, including its CJS globals.
// Its context layout affects bytecode size, so compiling a bare ESM module
// does not measure the functions the renderer tests actually execute.
function wrapModule(code) {
  const args = [
    "__vite_ssr_exports__", "__vite_ssr_import_meta__", "__vite_ssr_import__",
    "__vite_ssr_dynamic_import__", "__vite_ssr_exportAll__", "__vite_ssr_exportName__",
    "__filename", "__dirname", "module", "exports", "require",
  ];
  return `'use strict';async (${args.join(",")})=>{{${code}\n}}`;
}

async function compileModules() {
  // Compilation runs in a disposable --no-lazy child, never executing the
  // wrapped application modules or changing the parent/test runtime's tiers.
  for await (const line of createInterface({ input: process.stdin })) {
    const { file, variant, code } = JSON.parse(line);
    writeSync(1, `@@FILE ${JSON.stringify({ file, variant })}\n`);
    setFlagsFromString("--print-bytecode --print-bytecode-filter=*");
    try {
      new Script(code, { filename: file });
    } finally {
      setFlagsFromString("--no-print-bytecode");
    }
  }
}

async function checkBytecode() {
  const { createVitest } = await import("vitest/node");
  const viteRequire = createRequire(import.meta.resolve("vite"));
  const { minifySync } = await import(viteRequire.resolve("rolldown/utils"));
  const context = await createVitest({
    root: repoRoot,
    config: resolve(repoRoot, "vitest.workspace.ts"),
    project: ["desktop-renderer"],
    watch: false,
  });
  let child;
  try {
    await context.standalone();
    const environment = context.projects[0]?.vite.environments.ssr;
    if (!environment) throw new Error("The desktop-renderer SSR environment is missing");
    const modules = [];
    for (const [, file] of components) {
      const result = await environment.fetchModule(resolve(repoRoot, file));
      if (!("code" in result)) throw new Error(`No transformed code for ${file}`);
      const code = wrapModule(result.code);
      modules.push({ file, variant: "Vitest", code });
      // Preserve the wrapper as an observable value during compression. This
      // assignment is only compiled, never executed or installed on globalThis.
      const minified = minifySync(file, code.replace("async (", "globalThis.__rendererBytecodeModule = async ("), {
        compress: true,
        mangle: false,
      });
      if (minified.errors.length > 0) throw new Error(`Could not minify ${file}`);
      modules.push({ file, variant: "minified", code: minified.code });
    }

    child = spawn(process.execPath, ["--no-lazy", scriptPath, "--compile"], {
      cwd: repoRoot,
      stdio: ["pipe", "pipe", "pipe"],
    });
    const finished = once(child, "close");
    let diagnostics = "";
    child.stderr.on("data", (chunk) => {
      diagnostics = (diagnostics + chunk).slice(-4000);
    });
    const records = [];
    let file;
    let variant;
    let name;
    const output = createInterface({ input: child.stdout });
    output.on("line", (line) => {
      if (line.startsWith("@@FILE ")) ({ file, variant } = JSON.parse(line.slice(7)));
      else if (line.startsWith("[generated bytecode for function: ")) {
        name = /^\[generated bytecode for function: (.*?) \(0x/.exec(line)?.[1];
      } else if (file && line.startsWith("Bytecode length: ")) {
        records.push({ file, variant, name: name || "(anonymous)", bytes: Number(line.slice(17)) });
      }
    });
    // Disassembly is reduced as it streams; never buffer or print it in CI.
    for (const module of modules) {
      if (!child.stdin.write(JSON.stringify(module) + "\n")) await once(child.stdin, "drain");
    }
    child.stdin.end();
    const [exitCode] = await finished;
    if (exitCode !== 0) throw new Error(`Bytecode compiler exited ${exitCode}: ${diagnostics}`);

    for (const [component, file] of components) {
      const record = records.find((entry) => entry.file === file && entry.variant === "Vitest" && entry.name === component);
      if (!record) throw new Error(`V8 did not report bytecode for ${component}`);
      const minified = records.filter((entry) => entry.file === file && entry.variant === "minified");
      if (minified.length < 2) throw new Error(`V8 did not report minified functions for ${file}`);
      const maximum = Math.max(...minified.map((entry) => entry.bytes));
      console.log(`${component}: ${record.bytes.toLocaleString("en-US")} bytes; minified file maximum ${maximum.toLocaleString("en-US")}`);
    }
    const failures = records.filter((record) => !Number.isInteger(record.bytes) || record.bytes > bytecodeBudget);
    for (const record of failures) {
      console.error(`${record.file}: ${record.name} (${record.variant}) uses ${record.bytes} bytes (budget ${bytecodeBudget})`);
    }
    if (failures.length > 0) {
      throw new Error(`${failures.length} renderer functions exceed the ${bytecodeBudget}-byte budget`);
    }
    console.log(`Renderer bytecode budget passed for all ${records.length} compiled functions`);
  } finally {
    if (child && child.exitCode === null) child.kill();
    await context.close();
  }
}

try {
  if (process.argv[2] === "--compile") await compileModules();
  else await checkBytecode();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
