import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import type { CodexEnvironmentDocument } from "@pwragent/shared";
import {
  createCodexEnvironmentDocumentSource,
  listCodexEnvironmentFiles,
  readCodexEnvironmentDocumentSource,
  readCodexEnvironmentFile,
  saveCodexEnvironmentFile,
  writeCodexEnvironmentDocumentSource,
} from "../app-server/codex-environment-editor";
import { listCodexEnvironmentOptions } from "../app-server/codex-environment-config";

const REPO_ENVIRONMENT = path.resolve(
  import.meta.dirname,
  "../../../../../.codex/environments/environment.toml",
);

function read(source: string): CodexEnvironmentDocument {
  const result = readCodexEnvironmentDocumentSource(source);
  if (result.status !== "ok") {
    throw new Error(`unreadable: ${result.message}`);
  }
  return result.document;
}

const COMMENTED = [
  "# THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY",
  "version = 1",
  "name = \"Demo\" # shown in the chip",
  "owner = \"platform-team\"",
  "",
  "# Install first.",
  "[setup]",
  "script = '''",
  "pnpm install",
  "'''",
  "timeout = 30",
  "",
  "[setup.win32]",
  "script = \"pnpm.cmd install\"",
  "",
  "[team]",
  "channel = \"#builds\"",
  "",
  "# Dev server, macOS only.",
  "[[actions]]",
  "name = \"Dev\"",
  "icon = \"run\"",
  "command = \"pnpm dev\"",
  "platform = \"darwin\"",
  "port = 3000",
  "",
  "[[actions]]",
  "name = \"Test\"",
  "icon = \"test\"",
  "command = \"pnpm test\"",
  "",
].join("\n");

describe("codex environment editor: reading", () => {
  it("reads the repository's environment as per-platform setup and grouped actions", async () => {
    const document = read(await readFile(REPO_ENVIRONMENT, "utf8"));
    expect(document.name).toBe("PwrAgent");
    expect(document.setup.mode).toBe("perPlatform");
    expect(document.setup.script).toContain("nvm install");
    expect(Object.keys(document.setup.platformScripts)).toEqual(["win32"]);
    expect(document.cleanup.script).toBe("rm -rf node_modules");
    expect(document.actions.map((action) => action.name)).toEqual([
      "Work",
      "Dev - Messaging",
      "Dev - No Messaging",
      "Default - No Messaging",
      "Dev - Protocol Capture",
      "React DevTools - Standalone",
      "Dev - React DevTools",
    ]);
    const [work] = document.actions;
    expect(work.mode).toBe("perPlatform");
    expect(Object.keys(work.platformCommands)).toEqual(["darwin", "linux", "win32"]);
    expect(work.sourceEntries).toEqual({ darwin: 0, linux: 1, win32: 2 });
    expect(work.icon).toBe("run");
  });

  it("keeps a platform-less action shared and splits same-name entries that are not adjacent", () => {
    const document = read([
      "name = \"x\"",
      "[[actions]]", "name = \"Run\"", "platform = \"darwin\"", "command = \"a\"",
      "[[actions]]", "name = \"Shared\"", "command = \"b\"",
      "[[actions]]", "name = \"Run\"", "platform = \"linux\"", "command = \"c\"",
    ].join("\n"));
    expect(document.actions.map((action) => [action.name, action.mode])).toEqual([
      ["Run", "perPlatform"],
      ["Shared", "shared"],
      ["Run", "perPlatform"],
    ]);
  });

  it("reports a value it can't read with its line", () => {
    const result = readCodexEnvironmentDocumentSource([
      "name = \"x\"",
      "[[actions]]",
      "name = \"Seed\"",
      "command = { run = \"pnpm seed\" }",
    ].join("\n"));
    expect(result).toMatchObject({ status: "unreadable", line: 4 });
  });

  it("refuses an action for a platform it doesn't know", () => {
    const result = readCodexEnvironmentDocumentSource([
      "[[actions]]", "name = \"Run\"", "platform = \"freebsd\"", "command = \"a\"",
    ].join("\n"));
    expect(result).toMatchObject({ status: "unreadable", line: 3 });
  });
});

describe("codex environment editor: writing", () => {
  it("leaves every byte alone when nothing changed", async () => {
    const repo = await readFile(REPO_ENVIRONMENT, "utf8");
    expect(writeCodexEnvironmentDocumentSource(repo, read(repo))).toBe(repo);
    expect(writeCodexEnvironmentDocumentSource(COMMENTED, read(COMMENTED))).toBe(COMMENTED);
    const crlf = COMMENTED.replace(/\n/g, "\r\n");
    expect(writeCodexEnvironmentDocumentSource(crlf, read(crlf))).toBe(crlf);
  });

  it("rewrites only the edited value and keeps its trailing comment", () => {
    const document = read(COMMENTED);
    document.name = "Demo app";
    document.actions[1].command = "pnpm test --watch=false";
    const next = writeCodexEnvironmentDocumentSource(COMMENTED, document);
    const changed = diffLines(COMMENTED, next);
    expect(changed).toEqual([
      ["name = \"Demo\" # shown in the chip", "name = \"Demo app\" # shown in the chip"],
      ["command = \"pnpm test\"", "command = \"pnpm test --watch=false\""],
    ]);
  });

  it("moves whole action entries, with their comments and unknown keys, when reordered", () => {
    const document = read(COMMENTED);
    document.actions.reverse();
    const next = writeCodexEnvironmentDocumentSource(COMMENTED, document);
    expect(next).toContain([
      "[[actions]]",
      "name = \"Test\"",
      "icon = \"test\"",
      "command = \"pnpm test\"",
      "",
      "# Dev server, macOS only.",
      "[[actions]]",
      "name = \"Dev\"",
      "icon = \"run\"",
      "command = \"pnpm dev\"",
      "platform = \"darwin\"",
      "port = 3000",
      "",
    ].join("\n"));
    expect(next.startsWith(COMMENTED.slice(0, COMMENTED.indexOf("# Dev server")))).toBe(true);
    expect(read(next).actions.map((action) => action.name)).toEqual(["Test", "Dev"]);
  });

  it("adds and deletes actions", () => {
    const document = read(COMMENTED);
    document.actions = [
      document.actions[0],
      {
        key: "new",
        name: "Lint",
        icon: "tool",
        mode: "shared",
        command: "pnpm lint",
        platformCommands: {},
      },
      { key: "blank", name: "", icon: "tool", mode: "shared", command: "", platformCommands: {} },
    ];
    const next = writeCodexEnvironmentDocumentSource(COMMENTED, document);
    expect(next).not.toContain("pnpm test");
    expect(next).toContain("port = 3000");
    expect(next.endsWith([
      "[[actions]]",
      "name = \"Lint\"",
      "icon = \"tool\"",
      "command = \"pnpm lint\"",
      "",
    ].join("\n"))).toBe(true);
    expect(read(next).actions.map((action) => action.name)).toEqual(["Dev", "Lint"]);
  });

  it("removes every action without leaving blank lines behind", () => {
    const document = read(COMMENTED);
    document.actions = [];
    const next = writeCodexEnvironmentDocumentSource(COMMENTED, document);
    expect(next.endsWith("[team]\nchannel = \"#builds\"\n")).toBe(true);
  });

  it("reorders the repository's grouped actions and reads them back the same", async () => {
    const repo = await readFile(REPO_ENVIRONMENT, "utf8");
    const document = read(repo);
    const [first, ...rest] = document.actions;
    document.actions = [...rest, first];
    const reread = read(writeCodexEnvironmentDocumentSource(repo, document));
    expect(reread.actions.map((action) => [action.name, action.platformCommands]))
      .toEqual(document.actions.map((action) => [action.name, action.platformCommands]));
    expect(reread.setup).toEqual(document.setup);
  });

  it("splits an action into per-platform entries and joins them back", () => {
    const document = read(COMMENTED);
    const test = document.actions[1];
    test.mode = "perPlatform";
    test.platformCommands = { darwin: "pnpm test", win32: "pnpm.cmd test" };
    const split = writeCodexEnvironmentDocumentSource(COMMENTED, document);
    const reread = read(split);
    expect(reread.actions[1]).toMatchObject({
      name: "Test",
      mode: "perPlatform",
      platformCommands: { darwin: "pnpm test", win32: "pnpm.cmd test" },
    });
    reread.actions[1].mode = "shared";
    reread.actions[1].command = "pnpm test";
    const joined = writeCodexEnvironmentDocumentSource(split, reread);
    expect(joined).toBe(COMMENTED);
  });

  it("removes platform scripts when setup goes back to one script, and keeps other keys", () => {
    const document = read(COMMENTED);
    document.setup.mode = "shared";
    const next = writeCodexEnvironmentDocumentSource(COMMENTED, document);
    expect(next).not.toContain("[setup.win32]");
    expect(next).toContain("timeout = 30");
    expect(next).toContain("[team]\nchannel = \"#builds\"");
    expect(next).toContain("owner = \"platform-team\"");
  });

  it("adds a platform script after the setup tables", () => {
    const document = read(COMMENTED);
    document.setup.platformScripts.darwin = "brew bundle\npnpm install";
    const next = writeCodexEnvironmentDocumentSource(COMMENTED, document);
    expect(next).toContain([
      "[setup.win32]",
      "script = \"pnpm.cmd install\"",
      "",
      "[setup.darwin]",
      "script = '''",
      "brew bundle",
      "pnpm install'''",
      "",
      "[team]",
    ].join("\n"));
    expect(read(next).setup.platformScripts).toEqual({
      win32: "pnpm.cmd install",
      darwin: "brew bundle\npnpm install",
    });
  });

  it("does not write a platform script that matches the default", () => {
    const document = read(COMMENTED);
    document.setup.platformScripts.linux = document.setup.script;
    expect(writeCodexEnvironmentDocumentSource(COMMENTED, document)).toBe(COMMENTED);
  });

  it("keeps an empty platform script the operator did not touch", () => {
    const source = "[setup]\nscript = \"a\"\n[setup.win32]\nscript = \"\"\n";
    expect(writeCodexEnvironmentDocumentSource(source, read(source))).toBe(source);
  });

  it.each([
    ["ends with a quote", "echo 'done'"],
    ["contains triple single quotes", "cat <<'''\nx\n'''"],
    ["contains quotes and backslashes", "printf \"%s\\n\" \"a\"\necho \"\"\"three\"\"\""],
    ["has a tab and unicode", "echo\t\"héllo ✓\"\nexit 0"],
  ])("round-trips a script that %s", (_label, script) => {
    const document = read(COMMENTED);
    document.setup.script = script;
    const next = writeCodexEnvironmentDocumentSource(COMMENTED, document);
    expect(read(next).setup.script).toBe(script);
  });

  it("creates a new file with only what was entered", () => {
    const source = createCodexEnvironmentDocumentSource({
      name: "Node",
      setup: { mode: "shared", script: "pnpm install", platformScripts: {} },
      cleanup: { mode: "shared", script: "", platformScripts: {} },
      actions: [{
        key: "a",
        name: "Dev",
        icon: "run",
        mode: "shared",
        command: "pnpm dev",
        platformCommands: {},
      }],
    });
    expect(source).toBe([
      "version = 1",
      "name = \"Node\"",
      "",
      "[setup]",
      "script = \"pnpm install\"",
      "",
      "[[actions]]",
      "name = \"Dev\"",
      "icon = \"run\"",
      "command = \"pnpm dev\"",
      "",
    ].join("\n"));
  });

  it("writes a file the runtime reads the same way", async () => {
    const root = await mkdtemp(path.join(os.tmpdir(), "pwragent-env-editor-roundtrip-"));
    try {
      const document = read(COMMENTED);
      document.actions[1].mode = "perPlatform";
      document.actions[1].platformCommands = { linux: "pnpm test", win32: "pnpm.cmd test" };
      await mkdir(path.join(root, ".codex/environments"), { recursive: true });
      await writeFile(
        path.join(root, ".codex/environments/demo.toml"),
        writeCodexEnvironmentDocumentSource(COMMENTED, document),
      );
      const [win] = await listCodexEnvironmentOptions(root, "win32");
      expect(win.setupScript).toBe("pnpm.cmd install");
      expect(win.actions.map((action) => action.command)).toEqual(["pnpm.cmd test"]);
      const [mac] = await listCodexEnvironmentOptions(root, "darwin");
      expect(mac.setupScript).toBe("pnpm install");
      expect(mac.actions.map((action) => action.command)).toEqual(["pnpm dev"]);
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
});

describe("codex environment editor: files", () => {
  let root: string;
  let environments: string;

  beforeEach(async () => {
    root = await mkdtemp(path.join(os.tmpdir(), "pwragent-env-editor-"));
    environments = path.join(root, ".codex", "environments");
    await mkdir(environments, { recursive: true });
  });

  afterEach(async () => {
    await rm(root, { recursive: true, force: true });
  });

  it("lists files with a summary, and an unreadable file with its line", async () => {
    await writeFile(path.join(environments, "environment.toml"), COMMENTED);
    await writeFile(path.join(environments, "legacy.toml"), "name = \"x\"\nflags = [1, 2]\n");
    await writeFile(path.join(environments, "notes.md"), "ignored");
    const result = await listCodexEnvironmentFiles(root);
    expect(result.files).toEqual([
      { fileName: "environment.toml", name: "Demo", setupPlatforms: ["win32"], actionCount: 2 },
      {
        fileName: "legacy.toml",
        setupPlatforms: [],
        actionCount: 0,
        error: { message: "Line 2 has a value PwrAgent can't read.", line: 2 },
      },
    ]);
  });

  it("lists nothing for a project without the folder", async () => {
    await rm(path.join(root, ".codex"), { recursive: true, force: true });
    expect((await listCodexEnvironmentFiles(root)).files).toEqual([]);
  });

  it("saves against the revision it read and refuses a stale one", async () => {
    await writeFile(path.join(environments, "environment.toml"), COMMENTED);
    const opened = await readCodexEnvironmentFile({ directoryPath: root, fileName: "environment.toml" });
    if (opened.status !== "ok") throw new Error("expected ok");
    opened.document.name = "Renamed";
    const saved = await saveCodexEnvironmentFile({
      directoryPath: root,
      fileName: "environment.toml",
      document: opened.document,
      expectedRevision: opened.revision,
    });
    expect(saved).toMatchObject({ status: "saved", document: { name: "Renamed" } });
    expect(await readFile(path.join(environments, "environment.toml"), "utf8"))
      .toContain("name = \"Renamed\" # shown in the chip");

    const stale = await saveCodexEnvironmentFile({
      directoryPath: root,
      fileName: "environment.toml",
      document: opened.document,
      expectedRevision: opened.revision,
    });
    expect(stale).toEqual({ status: "conflict" });
  });

  it("creates a file, and refuses a name that exists", async () => {
    const document: CodexEnvironmentDocument = {
      name: "Docs",
      setup: { mode: "shared", script: "", platformScripts: {} },
      cleanup: { mode: "shared", script: "", platformScripts: {} },
      actions: [],
    };
    await rm(path.join(root, ".codex"), { recursive: true, force: true });
    const created = await saveCodexEnvironmentFile({ directoryPath: root, fileName: "docs.toml", document });
    expect(created).toMatchObject({ status: "saved" });
    expect(await readFile(path.join(environments, "docs.toml"), "utf8")).toBe("version = 1\nname = \"Docs\"\n");
    expect(await saveCodexEnvironmentFile({ directoryPath: root, fileName: "docs.toml", document }))
      .toEqual({ status: "exists" });
  });

  it("refuses invalid documents and unsafe file names", async () => {
    const document: CodexEnvironmentDocument = {
      name: " ",
      setup: { mode: "shared", script: "", platformScripts: {} },
      cleanup: { mode: "shared", script: "", platformScripts: {} },
      actions: [{ key: "a", name: "Lint", icon: "tool", mode: "shared", command: "", platformCommands: {} }],
    };
    expect(await saveCodexEnvironmentFile({ directoryPath: root, fileName: "x.toml", document }))
      .toEqual({
        status: "invalid",
        problems: [
          { field: "name", message: "Enter a name." },
          { field: "action:a", message: "Add a command, or delete this action." },
        ],
      });
    await expect(saveCodexEnvironmentFile({
      directoryPath: root,
      fileName: "../escape.toml",
      document: { ...document, name: "x", actions: [] },
    })).rejects.toThrow(/file name/i);
    await expect(readCodexEnvironmentFile({ directoryPath: root, fileName: "sub/x.toml" }))
      .rejects.toThrow(/file name/i);
  });

  it("reports an unreadable file with the lines around the problem", async () => {
    await writeFile(path.join(environments, "legacy.toml"), "a = \"1\"\nb = \"2\"\nc = [1]\nd = \"4\"\n");
    const result = await readCodexEnvironmentFile({ directoryPath: root, fileName: "legacy.toml" });
    expect(result).toMatchObject({
      status: "unreadable",
      line: 3,
      excerpt: [
        { line: 1, text: "a = \"1\"" },
        { line: 2, text: "b = \"2\"" },
        { line: 3, text: "c = [1]" },
        { line: 4, text: "d = \"4\"" },
        { line: 5, text: "" },
      ],
    });
  });
});

function diffLines(before: string, after: string): Array<[string, string]> {
  const a = before.split("\n");
  const b = after.split("\n");
  expect(b).toHaveLength(a.length);
  return a.flatMap((line, index) => (line === b[index] ? [] : [[line, b[index]] as [string, string]]));
}
