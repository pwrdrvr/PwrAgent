import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { expect, it } from "vitest";

const sources = [
  "Composer.tsx",
  "useComposerScheduleMenu.ts",
  "useComposerSendPreparation.ts",
  "useComposerWorkspaceHandoffState.ts",
].map((name) => readFileSync(fileURLToPath(new URL(`../../renderer/src/features/composer/${name}`, import.meta.url)), "utf8"));
const compiled = sources.map((source) => ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.CommonJS,
    jsx: ts.JsxEmit.ReactJSXDev,
  },
}).outputText);

it.each(["Composer*", "useComposer*", "renderComposer*"])(
  "keeps %s below V8's optimization limit with room for development JSX",
  (filter) => {
    // Compile without executing: no DOM, IPC, or module imports are needed.
    // V8 is the oracle, rather than source lines or machine-dependent timings.
    const result = spawnSync(process.execPath, [
      "--no-lazy",
      "--print-bytecode",
      `--print-bytecode-filter=${filter}`,
      "-e",
      'for (const source of JSON.parse(require("node:fs").readFileSync(0, "utf8"))) new (require("node:vm").Script)(source)',
    ], { input: JSON.stringify(compiled), encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });
    expect(result.error).toBeUndefined();
    expect(result.status, result.stderr).toBe(0);
    const functions = [...result.stdout.matchAll(/generated bytecode for function: (\w+) [^\n]+\nBytecode length: (\d+)/g)]
      .map((match) => ({ name: match[1], bytes: Number(match[2]) }));
    expect(functions.length).toBeGreaterThan(0);
    // TurboFan's limit is 61,440 bytes. Leave headroom for Vite's SSR import
    // wrappers and future controls; the development runtime captures a stack
    // for every JSX element, so an oversized Sparkplug frame penalizes them all.
    expect(functions.filter((fn) => fn.bytes >= 48 * 1024)).toEqual([]);
  },
);
